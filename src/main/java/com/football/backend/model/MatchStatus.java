package com.football.backend.model;

public enum MatchStatus {
    DRAFT,      // Черновик (видит только организатор)
    OPEN,       // Опубликован (идет набор)
    IN_PROGRESS, // Матч идет прямо сейчас (составы заблокированы)
    CANCELLED,       // Отменен организатором
    RESULT_PENDING,  // Протокол отправлен, идет трехчасовое голосование
    RESULT_DISPUTED, // Порог подтверждений не набран, требуется решение администратора
    RESULT_REJECTED, // Протокол отклонен администратором
    COMPLETED        // Результат подтвержден и статистика начислена
}
